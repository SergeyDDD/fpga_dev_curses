static const uint8_t *find_glyph(uint32_t codepoint)
{
    uint32_t glyph_index;

    if (codepoint >= 32U && codepoint <= 126U)
        return ascii_font[codepoint - 32U];

    if (codepoint == 0x2019U || codepoint == 0x02BCU)
        return ascii_font['\'' - 32];

    for (glyph_index = 0; glyph_index < sizeof(ukrainian_font) / sizeof(ukrainian_font[0]); glyph_index++) {
        if (ukrainian_font[glyph_index].codepoint == codepoint)
            return ukrainian_font[glyph_index].columns;
    }
    return ascii_font['?' - 32];
}

static uint32_t next_codepoint(const char **text)
{
    const uint8_t *bytes = (const uint8_t *)*text;
    uint32_t codepoint, minimum;
    uint8_t length, byte_index;

    if (bytes[0] < 0x80U) {
        *text += 1;
        return bytes[0];
    }
    if (bytes[0] >= 0xC2U && bytes[0] <= 0xDFU) {
        length = 2;
        minimum = 0x80U;
        codepoint = bytes[0] & 0x1FU;
    } else if (bytes[0] >= 0xE0U && bytes[0] <= 0xEFU) {
        length = 3;
        minimum = 0x800U;
        codepoint = bytes[0] & 0x0FU;
    } else if (bytes[0] >= 0xF0U && bytes[0] <= 0xF4U) {
        length = 4;
        minimum = 0x10000U;
        codepoint = bytes[0] & 7U;
    } else {
        *text += 1;
        return '?';
    }

    for (byte_index = 1; byte_index < length; byte_index++) {
        if (bytes[byte_index] == 0 || (bytes[byte_index] & 0xC0U) != 0x80U) {
            *text += 1;
            return '?';
        }
        codepoint = (codepoint << 6) | (bytes[byte_index] & 0x3FU);
    }
    *text += length;
    if (codepoint < minimum || codepoint > 0x10FFFFU ||
        (codepoint >= 0xD800U && codepoint <= 0xDFFFU))
        return '?';
    return codepoint;
}

void UI_Text_DrawChar(UI_Graph *graph, int32_t x, int32_t y, uint32_t codepoint,
                     uint8_t foreground, uint8_t background, uint8_t opaque)
{
    const uint8_t *glyph;
    int32_t column, row;
    int64_t pixel_x, pixel_y;
    uint8_t is_foreground;

    glyph = find_glyph(codepoint);
    for (column = 0; column < UI_TEXT_ADVANCE; column++) {
        pixel_x = (int64_t)x + column;
        if (pixel_x < 0 || pixel_x >= UI_GRAPH_WIDTH)
            continue;
        for (row = 0; row < UI_TEXT_GLYPH_HEIGHT; row++) {
            pixel_y = (int64_t)y + row;
            if (pixel_y < 0 || pixel_y >= UI_GRAPH_HEIGHT)
                continue;
            is_foreground = column < UI_TEXT_GLYPH_WIDTH && ((glyph[column] >> row) & 1U);
            if (is_foreground || opaque)
                UI_Graph_SetPixel(graph, (int32_t)pixel_x, (int32_t)pixel_y,
                                  is_foreground ? foreground : background);
        }
    }
}

void UI_Text_DrawString(UI_Graph *graph, int32_t x, int32_t y, const char *text,
                       uint8_t foreground, uint8_t background, uint8_t opaque)
{
    int64_t cursor_x = x;
    int64_t cursor_y = y;
    uint32_t codepoint;

    if (text == 0)
        return;

    while (*text != '\0') {
        codepoint = next_codepoint(&text);
        if (codepoint == '\n') {
            cursor_x = x;
            cursor_y += UI_TEXT_LINE_HEIGHT;
        } else if (codepoint == '\r') {
            cursor_x = x;
        } else {
            if (cursor_x >= INT32_MIN && cursor_x <= INT32_MAX &&
                cursor_y >= INT32_MIN && cursor_y <= INT32_MAX)
                UI_Text_DrawChar(graph, (int32_t)cursor_x, (int32_t)cursor_y, codepoint,
                                 foreground, background, opaque);
            cursor_x += UI_TEXT_ADVANCE;
        }

        if (cursor_y >= UI_GRAPH_HEIGHT)
            break;
    }
}
